--QUERY 1:  WRITE CASE FOR REVISED  SALARY??

SELECT CONCAT(CONCAT(FIRST_NAME ,' '),LAST_NAME) AS FULL_NAME , SALARY , JOB_ID ,
                    CASE(JOB_ID , WHEN 'IT_PROG' THEN SALARY*0.5,
					      WHEN 'SA_REP'THEN SALARY*0.3,
						  WHEN 'MK_MAN' THEN SALARY *0.6
						  ELSE SALARY END AS REVISED_SALARY)
FROM EMPLOYEES ;


--QUERY 2:  UPDATING COMMISSION PCT VALUES ?

SELECT E.FIRST_NAME , E.LAST_NAME , COMMISSION_PCT,
                  CASE COMMISSION_PCT WHEN   0 THEN 1
                       WHEN 0.1 THEN 0.12
                       WHEN 0.2 THEN 0.32
                       WHEN 0.3 THEN 0.4
                       WHEN 0.4 THEN 0.5
                       ELSE 0
                       END AS REVISED_COMMISSION
                       
FROM EMPLOYEES E ;


-- QUERY 3: SORT THE ROWS BY USING IT PROG FIRST , THEN SALES AND ST CLERKS ASC ORDER??

SELECT FIRST_NAME , LAST_NAME , DEPARTMENT_NAME , JOB_ID
FROM EMPLOYEES E LEFT OUTER JOIN DEPARTMENTS D
ON(E.DEPARTMENT_ID = D.DEPARTMENT_ID)
ORDER BY        CASE   WHEN JOB_ID LIKE '%IT%' THEN 1
                   WHEN JOB_ID LIKE '%SA%' THEN 2
				   WHEN JOB_ID LIKE '%ST' THEN 3
				   ELSE 4  END  ;
				   

--- QUERY 4: FIND EMPLOYEES WHERE FIRST_NAME STARTS WITH A OR B ??
				   
SELECT FIRST_NAME , LAST_NAME , DEPARTMENT_ID , JOB_ID
FROM EMPLOYEES
WHERE FIRST_NAME = CASE   WHEN FIRST_NAME LIKE 'A%' THEN FIRST_NAME
                           WHEN FIRST_NAME LIKE 'B%' THEN FIRST_NAME
                           END ;
						   
						   
---- QUERY 5: WRITE A QUERY DISPLAY EMPLOYEES WHOSE FIRST_NAME STARTS WITH S OR PHONE NUMBER HAS 515

SELECT FIRST_NAME, EMAIL, PHONE_NUMBER
FROM EMPLOYEES
WHERE 'Match' = CASE 
                  WHEN EMAIL LIKE 'S%' THEN 'Match'
                  WHEN PHONE_NUMBER LIKE '515%' THEN 'Match'
                  ELSE 'No Match'
                END;
                


--- QUERY 6: CATEGROIZED REGION AS POOR OR GOOD OR AVG 				
SELECT REGION_NAME ,
      CASE REGION_NAME   WHEN 'Europe' THEN 'GOOD_REGION'
                         WHEN 'Americas' THEN 'AVG_REGION'
                         WHEN 'Asia' THEN 'pooR_REGION'
                         WHEN 'Middle East and Africa' THEN 'VERY POOR REGION'
                         END  AS CAT_REGION
FROM REGIONS;


--- QUERY 7:   WRITE CASE FOR REVISED  SALARY?? USING DECODE ??


SELECT FIRST_NAME , LAST_NAME, SALARY,
       DECODE(JOB_ID, 'IT_PROG' , SALARY*5,
                      'PU MAN' , SALARY*6,
                      'MK MAN', SALARY*3, SALARY    ) REVISED_SALARY 
FROM EMPLOYEES;

-- QUERY 8:    DISPLAY SALARY TOTAL SALARY BY HANDLING NULL COMMISSIONS USING DECODE ??

SELECT FIRST_NAME , LAST_NAME  , COMMISSION_PCT ,
             DECODE(COMMISSION_PCT ,  NULL, 5,
			                         0.1, 2,
									 0.2, 3,
									 0.3, 4,
									 COMMISSION_PCT) REVISED_COMMISSION
									 
FROM EMPLOYEES;


-- QUERY 9:  WAQD THE REVISED SALARYS FOR IT DEPT , MARKETING, SHIPPING DEPT  USING DECODE??


SELECT FIRST_NAME , DEPARTMENT_NAME , JOB_ID,SALARY ,
             DECODE(DEPARTMENT_NAME , 'IT' , SALARY*12,
			                         'MARKETING' , SALARY*14,
									 'SHIPPING' , SALARY*13,(SALARY)*10)  ANNUAL_SALARY
             
FROM EMPLOYEES E JOIN DEPARTMENTS D
ON(E.DEPARTMENT_ID = D.DEPARTMENT_ID);


