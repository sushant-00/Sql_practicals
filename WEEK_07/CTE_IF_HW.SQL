--Q1 WRITE  A PROGRAM TO GET SALARY WISE RANK OF EMPLOYEES WITH RESPECT TO EVERY DEPARTMENT ??
SET SERVEROUTPUT ON 
DECLARE

USER_ID_01 NUMBER := &EMP_ID;
F_NAME VARCHAR2(20);
SAL NUMBER ;
DEPT_ID NUMBER ;
RNK_1 NUMBER;
EMP_ID NUMBER;

BEGIN 
WITH
DEPT_RANK
AS
(
  SELECT FIRST_NAME , SALARY , DEPARTMENT_ID , EMPLOYEE_ID ,
      DENSE_RANK()  OVER(PARTITION BY DEPARTMENT_ID ORDER BY SALARY DESC) AS RK
   FROM EMPLOYEES
)
SELECT FIRST_NAME , SALARY ,DEPARTMENT_ID ,EMPLOYEE_ID , RK
INTO F_NAME , SAL ,DEPT_ID ,EMP_ID,RNK_1
FROM DEPT_RANK
WHERE EMPLOYEE_ID = USER_ID_01;

DBMS_OUTPUT.PUT_LINE(F_NAME ||' '||SAL||' '||DEPT_ID||' '||RNK_1);

END; 

--  CREATE A BASIC CALCULATOR USING IF ELIF
SET SERVEROUTPUT ON 
DECLARE 
A NUMBER := &NUM1;
B NUMBER := &NUM2;
OPERATOR_S CHAR := &CH;
ADDS NUMBER ;
SUBS NUMBER ;
MULTI NUMBER ;
DIVSI NUMBER ;
MODULOUS NUMBER ;


BEGIN 

IF OPERATOR_S = '+'
    THEN 
    ADDS := A+B;
	DBMS_OUTPUT.PUT_LINE('THE ADDITION IS :'||' '||ADDS  );
ELSIF  OPERATOR_S = '-'
     THEN
     SUBS := A-B;
	 DBMS_OUTPUT.PUT_LINE('THE SUBSTRACTIONS IS:'||' '||SUBS);
ELSIF OPERATOR_S = '*'
     THEN 
     MULTI := A*B;
	 DBMS_OUTPUT.PUT_LINE('THE MULTIPLICATION IS '||' '||MULTI);
ELSIF OPERATOR_S = '/'
     THEN
     DIVSI := A/B;
     DBMS_OUTPUT.PUT_LINE('THE DIVISION IS '||' '||DIVSI);
ELSIF OPERATOR_S = '%'
      
      THEN
      MODULOUS := MOD(A, B);
     DBMS_OUTPUT.PUT_LINE('THE MODULOUS IS '||' '|| MODULOUS );
ELSE 
     DBMS_OUTPUT.PUT_LINE('INVALID NUMBER OR OPERATOR');

END IF;
END ;

 
