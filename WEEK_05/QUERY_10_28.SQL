QUERY 4: CITY WISE EMPLOYEES COUNT WHERE COUNT IS MORE THAN 2 AND SORT BY DESC ORDERES 

SELECT CITY , COUNT(EMPLOYEE_ID) AS CNT
FROM EMPLOYEES E JOIN DEPARTMENTS D
ON(E.DEPARTMENT_ID = D.DEPARTMENT_ID)

JOIN LOCATIONS L
ON(D.LOCATION_ID = L.LOCATION_ID)
GROUP BY CITY 
HAVING COUNT(EMPLOYEE_ID)> 2;




