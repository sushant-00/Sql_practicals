QUERY 6: DISPLAY JOB_ID WISE MIN , MAX , AND AVG SALARY FOR EMPLOYEES IN THE COMPANY
SELECT JOB_ID , MIN(SALARY) AS MIN_SAL , AVG(SALARY) AS AVG_SAL , MAX(SALARY) AS MAX_SAL
FROM EMPLOYEES 
WHERE SALARY > 1000
GROUP BY JOB_ID 
HAVING AVG(SALARY) > 5000;

