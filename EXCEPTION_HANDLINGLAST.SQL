---  USING CURORS INSIDE A FUNCTION 
CREATE OR REPLACE FUNCTION TOTAL_AMMOUT(CAT VARCHAR2)
RETURN NUMBER 
IS

--TOTAL_INFO VARCHAR2 ;
TOTAL_AMMOUNT NUMBER ;
REC PRODUCT_1%ROWTYPE ;

CURSOR P_INFO
IS
WITH 
PRODUCT_2
AS
(SELECT P_ID , P_NAME ,CATEGORY_S ,QUANTITY ,PRICE ,
ROW_NUMBER() OVER(PARTITION BY CATEGORY_S ORDER BY PRICE DESC) AS RNK 
FROM PRODUCT_1
)
SELECT  P_ID , P_NAME ,CATEGORY_S ,QUANTITY ,PRICE
FROM PRODUCT_2 
WHERE RNK  = 1
AND CATEGORY_S = CAT;

 

EXP_1 EXCEPTION ;
BEGIN
OPEN P_INFO ;


FETCH P_INFO INTO REC;
TOTAL_AMMOUNT  := REC.QUANTITY * REC.PRICE ;



CLOSE P_INFO;
RETURN TOTAL_AMMOUNT;




EXCEPTION 
WHEN EXP_1 
    THEN 
	  RAISE_APPLICATION_ERROR(-20030,'MULTIPLE VALUES RETURNED WHEN EXPECTED ONE ');
WHEN OTHERS
    THEN 
	DBMS_OUTPUT.PUT_LINE('UNEXCPETED ERRORS');
END;

