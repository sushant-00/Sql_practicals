CREATE OR REPLACE PROCEDURE P_LAST_EMP(DEPT_ID NUMBER , YEAR_1  VARCHAR2 )
AS
CURSOR LAST_EMP
IS
(SELECT FIRST_NAME , LAST_NAME , SALARY , HIRE_DATE , RNK
FROM (
SELECT FIRST_NAME , LAST_NAME , SALARY , HIRE_DATE ,
DENSE_RANK()  OVER(PARTITION by DEPARTMENT_ID ORDER BY HIRE_DATE DESC) AS RNK
FROM EMPLOYEES 
WHERE DEPARTMENT_ID = DEPT_ID 
AND  TO_CHAR(HIRE_DATE, 'YYYY') = YEAR_1
)
WHERE RNK = 1;
);
BEGIN
FOR EMP_S IN LAST_EMP
LOOP
DBMS_OUTPUT.PUT_LINE(EMP_S.FIRST_NAME || EMPS_S.LAST_NAME || EMP_S.SALARY || EMP_S.RNK);
END LOOP;

END ;




