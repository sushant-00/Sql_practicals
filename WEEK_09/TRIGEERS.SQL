CREATE TABLE TARGET_PRODUCTS(PRODUCT_ID NUMBER,
 PRODUCT_NAME VARCHAR2(20),
 QUANTITY NUMBER ,
  
 RATE  NUMBER ,
 NEW_RATE NUMBER,
 FINAL_AMOUNT NUMBER  ,
 NEW_FINAL_AMMOUNT NUMBER ,
 UPDATE_DATE DATE  , 
 INSERT_DATE DATE  , 
 DELETE_DATE DATE );
 
--3 CREATING A TRIGGER 

CREATE OR REPLACE TRIGGER  PRODUCT11_TRIG
AFTER 
INSERT OR UPDATE OR DELETE 
ON PRODUCTS_11
FOR EACH ROW

BEGIN 
IF INSERTING 
  THEN 
    INSERT INTO TARGET_PRODUCTS 
	VALUES(:NEW.PRODUCT_ID,:NEW.PRODUCT_NAME,:NEW.QUANTITY , :NEW.RATE,NULL,:NEW.FINAL_AMOUNT,NULL,NULL,SYSDATE,NULL);
	
END IF ;

IF UPDATING
   THEN 
   INSERT INTO TARGET_PRODUCTS
   VALUES(:OLD.PRODUCT_ID,:OLD.PRODUCT_NAME,:OLD.QUANTITY ,:OLD.RATE,:NEW.RATE,:OLD.FINAL_AMOUNT,:NEW.FINAL_AMOUNT,SYSDATE,NULL,NULL);
   
END IF ;

IF DELETING
    
   THEN 
    INSERT INTO TARGET_PRODUCTS
	VALUES(:OLD.PRODUCT_ID , :OLD.PRODUCT_NAME ,:OLD.QUANTITY , :OLD.RATE , NULL , :OLD.FINAL_AMOUNT , NULL,NULL ,NULL , SYSDATE);
END IF ;
END ;

