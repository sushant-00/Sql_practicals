CREATE OR REPLACE PROCEDURE P_COUNT(CT NUMBER )
AS
CAT_NAME VARCHAR2(30);
PRODUCT_COUNT NUMBER := 1;
COUNT_ZERO EXCEPTION ;
BEGIN
SELECT C.CATEGORY_NAME ,COUNT(ITEM_ID) AS CNT INTO CAT_NAME ,PRODUCT_COUNT 
FROM CATEGORIES C LEFT JOIN ITEMS I
ON(C.CAT_ID = I.CATEGORY_ID)
WHERE CAT_ID= CT
GROUP BY CATEGORY_NAME;

IF PRODUCT_COUNT = 0 
    THEN 
	RAISE COUNT_ZERO ;
END IF;

EXCEPTION
WHEN COUNT_ZERO
   THEN 
   DBMS_OUTPUT.PUT_LINE('AT LEAST 1 ITEM FOR EVERY CATEGORY');


END;

