CREATE OR REPLACE PROCEDURE PRODUCTS(P_ID ,C_ID ,ITEM_N ,UNIT_P , UNIT_M)
AS

CURSOR P_VALUES
IS
(SELECT ITEM_ID , ITEM_NAME , CATEGORY_ID ,UNIT_PRICE ,UOM
 FROM ITEMS 
 WHERE ITEM_ID = P_ID 
 AND CATEGORY_ID = C_ID 
);
NEG_UNIT_PRICE EXCEPTION
BEGIN 
FOR ITEM_1 IN P_VALUES
LOOP
UPDATE ITEMS 
SET ITEM_1.ITEM_NAME = ITEM_N , ITEM_1.UNIT_PRICE = UNIT_P , ITEM_1.UOM =UNIT_M
WHERE ITEM_1.ITEM_ID = P_ID

IF ITEM_1.UNIT_PRICE < 0
   THEN 
    RAISE NEG_UNIT_PRICE;
END IF;
IF UOM = 'LBS' OR  UOM = 'FT'
   THEN 
   RAISE UNIT_EXE;
END IF;




END LOOP;
