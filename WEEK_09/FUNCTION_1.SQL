--3 RETURN  TOTAL_SAL OF   THE EMPLOYEES WHEN SALARY IS GREATER THAN 10000 
CREATE OR REPLACE FUNCTION TOTAL_SAL_AFTER_TAX (SALARY NUMBER , COMM_PCT NUMBER  )
RETURN NUMBER 
AS 
TOTAL_SAL NUMBER := 0;
PF_SAL NUMBER := 400;
NET_ALLOWANCE NUMBER := 300 ;
BEGIN 

TOTAL_SAL := SALARY - PF_SAL - NET_ALLOWANCE ;
TOTAL_SAL := TOTAL_SAL +  SALARY * NVL(COMM_PCT , 0);
RETURN TOTAL_SAL;
END TOTAL_SAL_AFTER_TAX;

SELECT TOTAL_SAL_AFTER_TAX(1200 , 0.2) FROM DUAL;

