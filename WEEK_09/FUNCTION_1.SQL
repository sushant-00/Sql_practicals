CREATE OR REPLACE FUNCTION EMP_EXP_CAL( ID NUMBER)
RETURN NUMBER
AS

EXPER NUMBER ;

BEGIN 

SELECT ROUND(MONTHS_BETWEEN(SYSDTAE,HIRE_DATE)/12,0) AS EXP INTO EXPER
FROM EMPLOYEES
WHERE EMPLOYEE_ID = ID ;

RETURN EXPER  ;
END EMP_EXP_CAL ;
