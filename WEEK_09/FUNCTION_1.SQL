AS
EXP_1 NUMBER := 0;
EMP_TENURE VARCHAR2(20) ;
CURSOR EMP_DETAILS_DEPT
IS 
(SELECT EMPLOYEE_ID , FIRST_NAME , LAST_NAME , SALARY , HIRE_DATE
 FROM EMPLOYEES
 WHERE DEPARTMENT_ID = DEPT
);
