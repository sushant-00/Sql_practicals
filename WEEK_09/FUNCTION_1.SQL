CREATE OR REPLACE FUNCTION CALCULATOR_(A NUMBER , B NUMBER , OP CHAR)
RETURN NUMBER 
AS
BEGIN
IF OP = '+'
   THEN
    RETURN A + B ;
ELSIF OP = '-'
    THEN 
	RETURN A - B;
ELSIF  OP = '*'
    THEN 
	RETURN A*B;
ELSIF OP = '/'
    THEN 
	RETURN A/B;
ELSE 
   RETURN 0;
END IF ;
END CALCULATOR_;

