CREATE OR REPLACE FUNCTION GST_CAL(TOTAL_BILL NUMBER )
RETURN NUMBER 
AS
GRAND_TOTAL NUMBER :=TOTAL_BILL ;
SGST NUMBER := 0.10;
CGST NUMBER := 0.50;
BEGIN 
IF TOTAL_BILL > 100 
    THEN
	GRAND_TOTAL := GRAND_TOTAL  +( GRAND_TOTAL * SGST) + (GRAND_TOTAL * CGST);
    DBMS_OUTPUT.PUT_LINE(GRAND_TOTAL );
END IF ;
RETURN GRAND_TOTAL;
END GST_CAL;

