SET SERVEROUTPUT ON 
DECLARE
OD_ID NUMBER ;
ORDER_NAME VARCHAR2(20);
ORDERDATE DATE ;
CURSOR OD_INFO
IS
SELECT ORDER_ID , ITEMS_ORDERED , ORDERDER_DATE 
FROM FOOD_OD  A
WHERE  ORDER_TOTAL > (SELECT AVG(ORDER_TOTAL) 
                      FROM FOOD_OD D
					  WHERE A.C_ID = D.C_ID
);
BEGIN
IF OD_INFO%ISOPEN != TRUE
    THEN 
    OPEN OD_INFO ;
    DBMS_OUTPUT.PUT_LINE('CURSOR OPENED ');
END IF ;

    LOOP 
	FETCH OD_INFO INTO OD_ID , ORDER_NAME , ORDERDATE ;
	EXIT WHEN OD_INFO%NOTFOUND ;
	DBMS_OUTPUT.PUT_LINE(OD_ID||' '||ORDER_NAME||' '||ORDERDATE);
	DBMS_OUTPUT.PUT_LINE(OD_INFO%ROWCOUNT ||' '||'ROW FETCHED ');
	
    
END LOOP;
IF OD_INFO%ISOPEN 
   THEN 
    CLOSE OD_INFO;
    DBMS_OUTPUT.PUT_LINE('CURSOR CLOSED');
END IF;
END;


--- SELF JOIN IN CURSOR 
SET SERVEROUTPUT ON 
DECLARE
OD_ID NUMBER ;
C_ID NUMBER ;
ORDER_STATUS VARCHAR2(20) ;
CURSOR OD_INFO
AS
SELECT  DISTINCT D.ORDER_ID , D.C_ID , D.ORDER_STATUS 
FROM FOOD_OD D JOIN  FOOD_OD B 
ON (D.C_ID =B.C_ID AND D.ORDER_STATUS != 'DILIVERED' );

BEGIN
IF OD_INFO%ISOPEN != TRUE
    THEN 
    OPEN OD_INFO ;
    DBMS_OUTPUT.PUT_LINE('CURSOR OPENED ');
END IF ;

    LOOP 
	FETCH OD_INFO INTO OD_ID , C_ID , ORDERED_STATUS ;
	EXIT WHEN OD_INFO%NOTFOUND ;
	DBMS_OUTPUT.PUT_LINE(OD_ID||' '||C_ID||' '||ORDERED_STATUS);
	DBMS_OUTPUT.PUT_LINE(OD_INFO%ROWCOUNT ||' '||'ROW FETCHED ');
	
    
END LOOP;
IF OD_INFO%ISOPEN 
   THEN 
    CLOSE OD_INFO;
    DBMS_OUTPUT.PUT_LINE('CURSOR CLOSED');
END IF;
END;

