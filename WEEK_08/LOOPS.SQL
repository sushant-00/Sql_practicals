--- 2  WRITE A PROGRAM FOR ADDITTION OF FIRST 10 NUMBERS
SET SERVEROUTPUT ON 
DECLARE 
FIRST_NUM NUMBER := 0;
COUNTER NUMBER := 1;


BEGIN 
FIRST_NUM := FIRST_NUM + COUNTER;
COUNTER := COUNTER + 1;
EXIT WHEN FIRST_NUM = 10;
END LOOP;
DBMS_OUTPUT.PUT_LINE(FIRST_NUM);


END ;

