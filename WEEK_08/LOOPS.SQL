--  1  TAKE 2 INPUTS START_VAL AND END_VAL AND PRINT ALL VALUES BETWEEN THEM 
SET SERVEROUTPUT ON 
DECLARE 
CURR_VAL NUMBER := ST_VAL;
ST_VAL NUMBER := &ST;
END_VAL NUMBER := &ED_VAL;

BEGIN 
LOOP
DBMS_OUTPUT.PUT_LINE(CURR_VAL);
CURR_VAL := CURR_VAL + 1;

EXIT  WHEN ST_VAL > END_VAL;

END LOOP ;


END;

