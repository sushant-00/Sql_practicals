SET SERVEROUTPUT ON 
DECLARE
OD_ID NUMBER ;
ORDER_NAME VARCHAR2(20);
ORDERDATE DATE ;
CURSOR OD_INFO
IS
SELECT ORDER_ID , ITEMS_ORDERED , ORDERDER_DATE 
FROM FOOD_OD  A
WHERE  ORDER_TOTAL > (SELECT AVG(ORDER_TOTAL) 
                      FROM FOOD_OD D
					  WHERE A.C_ID = D.C_ID
);
BEGIN
IF OD_INFO%ISOPEN != TRUE
    THEN 
    OPEN OD_INFO ;
    DBMS_OUTPUT.PUT_LINE('CURSOR OPENED ');
END IF ;

    LOOP 
	FETCH OD_INFO INTO OD_ID , ORDER_NAME , ORDERDATE ;
	EXIT WHEN OD_INFO%NOTFOUND ;
	DBMS_OUTPUT.PUT_LINE(OD_ID||' '||ORDER_NAME||' '||ORDERDATE);
	DBMS_OUTPUT.PUT_LINE(OD_INFO%ROWCOUNT ||' '||'ROW FETCHED ');
	
    
END LOOP;
IF OD_INFO%ISOPEN 
   THEN 
    CLOSE OD_INFO;
    DBMS_OUTPUT.PUT_LINE('CURSOR CLOSED');
END IF;
END;
