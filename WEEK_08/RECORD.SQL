TYPE MANGO_DETAILS IS RECORD 
(
    F_NAME VARCHAR2(20),
    L_NAME VARCHAR2(20),
    SALARY NUMBER ,
    PREVIOUS_SAL NUMBER 
);
EMP_DETAILS MANGO_DETAILS ;
CURSOR CUS_2 
IS
(SELECT FIRST_NAME , LAST_NAME , SALARY  , PREVIOUS_SAL
FROM (
SELECT FIRST_NAME , LAST_NAME , SALARY , LAG(SALARY) OVER(PARTITION BY DEPARTMENT_ID ORDER BY SALARY DESC ) AS PREVIOUS_SAL
FROM EMPLOYEES 
)
WHERE SALARY = PREVIOUS_SAL
);
BEGIN 
OPEN CUS_2 ;
LOOP 
FETCH CUS_2 INTO  EMP_DETAILS; 
DBMS_OUTPUT.PUT_LINE(EMP_DETAILS.F_NAME || EMP_DETAILS.L_NAME || EMP_DETAILS.SALARY || EMP_DETAILS.PREVIOUS_SAL);
EXIT WHEN CUS_2%NOTFOUND ;
END LOOP ;
CLOSE CUS_2;
END;

