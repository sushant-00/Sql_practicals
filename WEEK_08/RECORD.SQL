DECLARE 
TYPE CUST_VAR IS RECORD 
( 
  ORDER_ID FOOD_OD.ORDER_ID%TYPE,
  ITEM_NAME FOOD_OD.ITEMS_ORDERED%TYPE,
  ORDER_TOTAL FOOD_OD.ORDER_TOTAL%TYPE,
  SECOND_OD NUMBER 
  
); 
FOOD_DETAILS CUST_VAR ;
CURSOR FOOD_1 
IS 
SELECT ORDER_ID , ITEMS_ORDERED , ORDER_TOTAL , RANK_2
FROM(
SELECT ORDER_ID , ITEMS_ORDERED  ,ORDER_TOTAL , DENSE_RANK() OVER(PARTITION BY C_ID ORDER BY ORDER_TOTAL DESC) AS RANK_2
FROM FOOD_OD 
)
WHERE RANK_2 = 2;
BEGIN
OPEN FOOD_1 ;
LOOP
FETCH FOOD_1 INTO FOOD_DETAILS; 
EXIT WHEN FOOD_1%NOTFOUND ;
DBMS_OUTPUT.PUT_LINE(FOOD_DETAILS.ORDER_ID || FOOD_DETAILS.ITEM_NAME ||FOOD_DETAILS.SECOND_OD);
END LOOP;
CLOSE FOOD_1;
END;

