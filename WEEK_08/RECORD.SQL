DECLARE
DEPT NUMBER := &DEPT;

TYPE EMP_INFO IS RECORD 
(  F_NAME VARCHAR2(20),
   L_NAME VARCHAR2(20),
   SALARY NUMBER 
) ;

EMP_DETAILS EMP_INFO;
CURSOR CUS_1 
IS 
SELECT FIRST_NAME , LAST_NAME , SALARY 
FROM EMPLOYEES 
WHERE DEPARTMENT_ID = DEPT;
BEGIN 
OPEN CUS_1;
LOOP
FETCH CUS_1 INTO EMP_DETAILS.F_NAME , EMP_DETAILS.L_NAME , EMP_DETAILS.SALARY ;
EXIT WHEN CUS_1%NOTFOUND ;
DBMS_OUTPUT.PUT_LINE(EMP_DETAILS.F_NAME ||' ' ||EMP_DETAILS.L_NAME||' '||EMP_DETAILS.SALARY);

END LOOP ;
CLOSE CUS_1;
END ;
