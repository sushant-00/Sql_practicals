8--MERGE WITH PROCEDURE 
CREATE OR REPLACE PROCEDURE FOOD_UPDATE (
    P_ORDER_ID      NUMBER,
    P_C_ID          NUMBER,
    P_ITEMS_ORDERED VARCHAR2,
    P_ORDER_TOTAL   NUMBER 
)
IS 
BEGIN 
    MERGE INTO TC_OR_SV TC
    USING DUAL 
    ON (TC.ORDER_ID = P_ORDER_ID)
    WHEN MATCHED THEN 
        UPDATE SET  
            TC.C_ID        = P_C_ID,
            TC.ITEMS_NAME  = P_ITEMS_ORDERED,
            TC.ORDER_TOTAL = P_ORDER_TOTAL,
            TC.UPDATE_DATE = SYSDATE 
    WHEN NOT MATCHED THEN 
        INSERT (ORDER_ID, C_ID, ITEMS_NAME, ORDER_TOTAL, UPDATE_DATE)
        VALUES (P_ORDER_ID, P_C_ID, P_ITEMS_ORDERED, P_ORDER_TOTAL,NULL);

    
END FOOD_UPDATE;

