--1   WAQD THE EMP INFO  WITH ANNUAL SAL AND  EXP  OF THOSE EMPLOYEES WORKING FOR MORE THAN 10 YRS AND MONTHLY SAL GRATER THAN 5000
SET SERVEROUTPUT ON 
CREATE OR REPLACE PROCEDURE EMP_ANNUAL_SAL
IS
TYPE EMP_DETAILS IS RECORD
( 
  F_NAME EMPLOYEES.FIRST_NAME%TYPE,
  L_NAME EMPLOYEES.LAST_NAME%TYPE,
  SALARY  EMPLOYEES.SALARY%TYPE,
  ANNUAL_SAL EMPLOYEES.SALARY%TYPE,
  EXP_5 NUMBER 
 
);

EMP_RECORD EMP_DETAILS;

CURSOR EMP_INFO 
IS
(  SELECT FIRST_NAME , LAST_NAME , SALARY , (SALARY + SALARY * NVL(COMMISSION_PCT  , 0))*12  AS ANNUAL_SAL , ROUND(MONTHS_BETWEEN(SYSDATE,HIRE_DATE)/12 , 1) AS EXP_1
   FROM EMPLOYEES 
   WHERE ROUND(MONTHS_BETWEEN(SYSDATE , HIRE_DATE)/12 , 1) > 10
   AND SALARY > 5000

);

BEGIN
OPEN EMP_INFO;
LOOP
FETCH EMP_INFO INTO  EMP_RECORD.F_NAME , EMP_RECORD.L_NAME , EMP_RECORD.SALARY , EMP_RECORD.ANNUAL_SAL , EMP_RECORD.EXP_5;
EXIT WHEN EMP_INFO%NOTFOUND;
DBMS_OUTPUT.PUT_LINE(EMP_RECORD.F_NAME||' '||EMP_RECORD.L_NAME ||' '||EMP_RECORD.SALARY||' '||EMP_RECORD.ANNUAL_SAL||' '||EMP_RECORD.EXP_5);
END LOOP;
CLOSE EMP_INFO ;
END EMP_ANNUAL_SAL;

EXECUTE  EMP_ANNUAL_SAL ;

