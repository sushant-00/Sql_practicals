9-- FIND CUST TYPE HIGH OR LW VALUE DEPANDING ON ORDER TOTAL FOR A GIVEN DATE 

SET SERVEROUTPUT ON 
CREATE OR REPLACE PROCEDURE FOOD_DETAILS( DATE_1 DATE , ORDER_VALUE NUMBER )
IS 
CURSOR CUS_FD
IS 
( SELECT ORDER_ID , C_ID , ITEMS_ORDERED , ORDER_TOTAL , CASE  WHEN ORDER_TOTAL <= 100 THEN 'LOW VALUE CUST '
                                                                WHEN ORDER_TOTAL <= 250 THEN 'AVG VALUE CUST '
																WHEN ORDER_TOTAL <= 500 THEN 'MID VALUE CUST'
																WHEN ORDER_TOTAL >= 1000 THEN 'HIGH VALUE CUST'
																ELSE  'OUTLIER CUST'
																END  AS  CUST_VALUE
																
  FROM ( 
        SELECT ORDER_ID , C_ID , ITEMS_ORDERED , ORDER_TOTAL 
        FROM FOOD_OD 
        WHERE ORDERDER_DATE >= DATE_1 - 10
    )
  WHERE ORDER_TOTAL > ORDER_VALUE
);
BEGIN 
FOR FOOD_ORDERS  IN CUS_FD 
LOOP
DBMS_OUTPUT.PUT_LINE(FOOD_ORDERS.ORDER_ID || FOOD_ORDERS.C_ID || FOOD_ORDERS.ITEMS_ORDERED || FOOD_ORDERS.ORDER_TOTAL ||FOOD_ORDERS.CUST_VALUE);
END LOOP;
END FOOD_DETAILS ;

EXECUTE FOOD_DETAILS('2-2-2026' , 20);

--10 WAQD TO PROCESS THE FOOD ORDER GIVEN BY CUSTOMER 

SET SERVEROUTPUT ON;

CREATE OR REPLACE PROCEDURE FOOD_OD_PROCESS(
    NAME_1      VARCHAR2,
    ITEM_NAME   VARCHAR2,
    QUANTITY    NUMBER,
    PARCEL      CHAR,
    AMMOUNT     NUMBER 
)
IS
    GST          NUMBER := 0.50; 
    GRAND_TOTAL  NUMBER := 0;
    ORDER_STATUS VARCHAR2(20);
BEGIN 
    
    GRAND_TOTAL := AMMOUNT + (AMMOUNT * GST);

    
    ORDER_STATUS := CASE  
                        WHEN GRAND_TOTAL > 1000 THEN 'PREMIUM'
                        WHEN GRAND_TOTAL > 500  THEN 'STANDARD'
                        ELSE 'ECONOMY'
                    END;

    
    IF PARCEL = 'Y' THEN 
        IF GRAND_TOTAL > 1000 THEN 
            
            DBMS_OUTPUT.PUT_LINE('FREE BAG || SAUCE INCLUDED');
        ELSE 
            
            GRAND_TOTAL := GRAND_TOTAL + 10;
        END IF;
    ELSIF PARCEL = 'N' THEN
        DBMS_OUTPUT.PUT_LINE('DINE-IN ORDER');
    END IF; 

  
    DBMS_OUTPUT.PUT_LINE('Item: ' || ITEM_NAME || ' | Qty: ' || QUANTITY || ' | Total: ' || GRAND_TOTAL || ' | Status: ' || ORDER_STATUS);

END FOOD_OD_PROCESS;


