FIND EMPLOYEES JOINED IN LEAP YEAR 
AND EARNING MORE THAN AVG SAL  OF THEIR DEPARTMENTS ??

WITH  LEAP_YEAR_EMP
AS
(
    SELECT  FIRST_NAME , LAST_NAME , SALARY ,JOB_ID , DEPARTMENT_ID
	FROM EMPLOYEES 
	WHERE MOD(TO_CHAR(HIRE_DATE , 'YYYY') , 4) = 0
),
EMP_AVG_SAL
AS
( 
  SELECT DEPARTMENT_ID , AVG(SALARY) AS AVG_SAL
  FROM LEAP_YEAR_EMP
  GROUP BY DEPARTMENT_ID
  
   
)
SELECT *
FROM  LEAP_YEAR_EMP LES JOIN EMP_AVG_SAL AE
ON(LES.DEPARTMENT_ID = AE.DEPARTMENT_ID
 AND LES.SALARY > AE.AVG_SAL);
 
 
