--4      WAQ TO DISPLAY DEPARTMENT NAME OF EMPLOYEE WORKING IN 90 DEPT AND WAS HIRED IN 2005



SET SERVEROUTPUT ON 
DECLARE 
EMP_ID VARCHAR2(20);
HIRE_DATE DATE ;
F_NM VARCHAR2(20);
L_NM VARCHAR2(20);
DEPT_ID NUMBER  := &DP;

BEGIN
SELECT FIRST_NAME , LAST_NAME , DEPARTMENT_ID   INTO F_NM , L_NM  , DEPT_ID
FROM EMPLOYEES
WHERE TO_CHAR(HIRE_DATE  , 'YYYY') = '2005'
AND DEPARTMENT_ID = DEPT_ID;

DBMS_OUTPUT.PUT_LINE(F_NM ||' '|| L_NM ||' '|| DEPT_ID );

IF DEPT_ID = 90  
  THEN 
  DBMS_OUTPUT.PUT_LINE('DEPARTMENT IS Executive AND WAS HIRED IN 2005');
  
END IF;
END ;


--5  WAQD  EMPLOYEE-WISE  COUNT  FOR A CITY  AND  IF COUNT IS GREATER THAN 10 PRINT CITY_WISE COUNT??

SET SERVEROUTPUT ON 
DECLARE 
CITY VARCHAR2(20) = &CT;
CNT_EMP NUMBER ;


BEGIN 

SELECT  CITY , COUNT(EMPLOYEE_ID) AS CNT INTO CITY , CNT_EMP
FROM EMPLOYEES E JOIN DEPARTMENTS D 
ON (E.DEPARTMENT_ID = D.DEPARTMENT_ID)

JOIN LOCATIONS L
ON (L.LOCATION_ID = D.LOCATION_ID)
WHERE CITY = &CT ---'Seattle'
GROUP BY CITY ;

IF CNT_EMP > 10
    THEN 
	DBMS_OUTPUT.PUT_LINE('CITY_WISE EMPLOYEE COUNT IS HIGH ');
	
END IF;



END ;











 
  
   








