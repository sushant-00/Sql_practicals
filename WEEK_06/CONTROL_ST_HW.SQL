-- 1   WAQD SALARY OF EMPLOEE IF IT IS GREATER THAN 20000 PRINT HIGH OR ELSE LOW ?

SET SERVEROUTPUT ON 
DECLARE
F_NM VARCHAR2(20);
L_NM VARCHAR2(20);
SAL NUMBER ;
EMP_1 NUMBER := &EM;

BEGIN
SELECT FIRST_NAME , LAST_NAME , SALARY  INTO  F_NM , L_NM , SAL
FROM EMPLOYEES
WHERE EMPLOYEE_ID = EMP_1;

IF SAL > 20000
 THEN 
 DBMS_OUTPUT.PUT_LINE('SALARY IS HIGH ');
 
ELSE 
   DBMS_OUTPUT.PUT_LINE('SALARY IS LOW');
   
END IF;
END;

--2 WAQ TO REVISE SALARY OF EMPLOYEE IF IS GREATER THAN 10000
SET SERVEROUTPUT ON 
DECLARE 
EMP_1 NUMBER := &ES;
F_NM VARCHAR2(20) ;
L_NM VARCHAR2(20);
SAL NUMBER;
BEGIN 

SELECT FIRST_NAME , LAST_NAME , SALARY  INTO  F_NM , L_NM , SAL
FROM EMPLOYEES
WHERE EMPLOYEE_ID = EMP_1;

