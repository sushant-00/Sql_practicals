DESC DEPT;

MERGE INTO EMP001 TRG
USING(

SELECT E.EMP_ID, E.FIRST_NAME, E.LAST_NAME, E.P_NUMBER, E.SALARY, E.DEPT_ID, 
       D.DEPT_NAME, D.MAN_ID, D.LOCATION_ID
FROM EMP E JOIN DEPT D
ON (E.DEPT_ID = D.DEPT_ID)

) SRC
ON (TRG.EMP_ID = SRC.EMP_ID)
WHEN MATCHED THEN 
UPDATE
SET TRG.FIRST_NAME = SRC.FIRST_NAME,
    TRG.LAST_NAME = SRC.LAST_NAME,
    TRG.P_NUMBER = SRC.P_NUMBER,
    TRG.SALARY = SRC.SALARY,
    TRG.DEPT_ID = SRC.DEPT_ID,
    TRG.DEPT_NAME = SRC.DEPT_NAME,
    TRG.MAN_ID = SRC.MAN_ID,
    TRG.LOCATION_ID = SRC.LOCATION_ID
WHEN NOT MATCHED THEN
INSERT VALUES(SRC.EMP_ID, SRC.FIRST_NAME, SRC.LAST_NAME, SRC.P_NUMBER, SRC.SALARY, SRC.DEPT_ID, 
SRC.DEPT_NAME, SRC.MAN_ID, SRC.LOCATION_ID);

