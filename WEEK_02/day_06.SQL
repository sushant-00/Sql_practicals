-- QUERY 13:
   -- WAQD THE TENURE YEARS OOF EMPOLYEES IF HIRE_DATE NOT GIVEN CONSIDER TO DAYS DATE??
SELECT FIRST_NAME, ROUND(MONTHS_BETWEEN(SYSDATE, COALESCE(HIRE_DATE, SYSDATE))/12,1) AS YEARS
FROM EMPLOYEES 
