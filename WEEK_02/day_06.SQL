-- WAQD count of employees who hired after year 2004    
    SELECT TO_CHAR(HIRE_DATE,'YYYY') AS JOINED_YEAR, COUNT(EMPLOYEE_ID) AS EMP_COUNT
    FROM EMPLOYEES
