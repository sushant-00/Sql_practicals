   QUERY 1:
   -- WAQD AREA CODE OF 650 FOR PHONE_NUMBER AND THOSE EMPLOYEE REOCRDS SORT BY EMPLOYEE_ID??
   SELECT FIRST_NAME , LAST_NAME ,
   SUBSTR(PHONE_NUMBER , 1,3) AS AREA_CODE 
   FROM EMPLOEES
   WHERE SUBSTR(PHONE_NUMBER , 1,3) = '650'
   ORDER BY EMPLOYEE_ID;
   
