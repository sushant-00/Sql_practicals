ORDER BY END_DATE;
 
-- QUERY 10:
   -- WAQD THE BONUS AND  ROUND OFF UPTO 2 DECIMAL PLACESS WHERE COMMISSION IS MORE THAN 1000 RUPPEE??
SELECT EMPLOYEE_ID,
ROUND(COMMISSION_PCT *SALARY , 2) AS ROUND_OFF_BONUS
FROM EMPLOYEES
WHERE (COMMISSION_PCT *SALARY) >1000
ORDER BY (COMMISSION_PCT *SALARY);
	  
