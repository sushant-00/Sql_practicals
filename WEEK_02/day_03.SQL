-- QUERY 1:
   -- WAQD Replace NULL commission with 0 FRO ALL EMPLOYEES WHO DONT EARN A commission
SELECT FIRST_NAME, SALARY, NVL(COMMISSION_PCT, 0) AS COMM_PCT
FROM EMPLOYEES 
ORDER BY SALARY DESC;

-- QUERY 2:
  -- WAQD THE  Label employees with AND without commission 
SELECT FIRST_NAME, NVL2(COMMISSION_PCT, 'HAS COMM', 'NO COMM') AS STATUS
FROM EMPLOYEES
ORDER BY FIRST_NAME;

-- QUERY 3:
  -- WAQD THE  Null commission if IT equals salary/10000 AS NEW COLUMN
SELECT FIRST_NAME, SALARY, NULLIF(COMMISSION_PCT, SALARY/10000) AS ADJUSTED_COMM
FROM EMPLOYEES
ORDER BY SALARY;

-- QUERY 4:
   -- WAQD THE Full name AND GIVE priority:last AND First RETURN ANY 1 IF THERE IS NULL PRESENT 
SELECT COALESCE(MIDDLE_NAME, LAST_NAME, FIRST_NAME) AS FULL_NAME
FROM EMPLOYEES
ORDER BY FULL_NAME;

-- QUERY 5:
   -- WAQD THE  Annual salary with commission
SELECT FIRST_NAME, ROUND((SALARY*12) + (SALARY*12*NVL(COMMISSION_PCT,0)), 2) AS ANNUAL_SALARY
FROM EMPLOYEES
ORDER BY ANNUAL_SALARY DESC;
 
 -- QUERY 6:
    -- WAQD THE EMPLOYEE TENURE AS PENDING OR ACTIVE 
SELECT FIRST_NAME, NVL2(HIRE_DATE, 'ACTIVE', 'PENDING') AS STATUS
FROM EMPLOYEES 
WHERE HIRE_DATE IS NOT NULL 
ORDER BY HIRE_DATE;

-- QUERY 7:
   -- WAQD THE  Null iF PHONE NUMBER IS NOT 10 OR MORE DIGITS??
SELECT FIRST_NAME, NULLIF(PHONE_NUMBER, SUBSTR(PHONE_NUMBER,1,3)) AS PHONE_CHECK
FROM EMPLOYEES
ORDER BY PHONE_NUMBER;

-- QUERY 8:
   -- WAQD THE TENURE YEARS OOF EMPOLYEES IF HIRE_DATE NOT GIVEN CONSIDER TO DAYS DATE??
SELECT FIRST_NAME, ROUND(MONTHS_BETWEEN(SYSDATE, COALESCE(HIRE_DATE, SYSDATE))/12,1) AS YEARS
FROM EMPLOYEES 
ORDER BY YEARS DESC;

-- QUERY 9:
   -- WAQD THE   NEXT PAYDAY AND HANDLE NULL HIRE_DATE FOR EVERY EMPLOYEES
SELECT FIRST_NAME, NEXT_DAY(NVL(HIRE_DATE, SYSDATE), 'FRIDAY') AS PAYDAY
FROM EMPLOYEES 
ORDER BY PAYDAY;
 

--QUERY 10:
  -- WAQD THE MANAGER STATUS FOR EVERY EMPOLYEE AND IF NO MANAGER RETURN AS NO MAGR??
SELECT FIRST_NAME , NVL2(MANAGER_ID, 'HAS MGR', 'NO MGR') AS STATUS
FROM EMPLOYEES 
ORDER BY MANAGER_ID NULLS LAST;

-- QUERY 11:
-- WAQD THE EMAILS AND IF NO EMAIL IS PRESENT REPLACE IT WITH FIRST AND LAST NAME ??
SELECT COALESCE(EMAIL, UPPER(FIRST_NAME)||'.'||LAST_NAME||'@ORACLE.COM') AS EMAIL
FROM EMPLOYEES 
ORDER BY LAST_NAME;

-- QUERY 12:
   -- WAQD NVL commission with ROUND salary AS BONUS FOR EVERY EMPLOYEE
SELECT FIRST_NAME, ROUND(NVL(COMMISSION_PCT*SALARY, SALARY*0.05), 2) AS BONUS
FROM EMPLOYEES
ORDER BY BONUS DESC;

-- QUERY 13:
   -- WAQD  NANE AND HIRE DATE AND REPLACE NULL WITH CURRENT DATE WHERE EMPLOYEES BETWEEN 100 AND 200??
SELECT FIRST_NAME, NVL2(HIRE_DATE, HIRE_DATE, SYSDATE) AS HIRE_WEEK
FROM EMPLOYEES 
WHERE EMPLOYEE_ID BETWEEN 100 AND 200
ORDER BY HIRE_WEEK;

-- QUERY 14:
  -- WAQD THE  LENGTH OF FIRST CHARACTER IF THE LENGTH IS SAME DISPLAY NULL??
SELECT NULLIF(LENGTH(FIRST_NAME), LENGTH(LAST_NAME)) AS NAME_LEN_DIFF
FROM EMPLOYEES 
ORDER BY NAME_LEN_DIFF;

-- QUERY 15:
   -- WAQD THE  COALESCE AND ADD_MONTHS AS  Probation end
SELECT FIRST_NAME, ADD_MONTHS(COALESCE(HIRE_DATE, SYSDATE), 6) AS PROBATION_END
FROM EMPLOYEES
ORDER BY PROBATION_END;

-- QUERY 16:
   -- WAQD THE MONTH END SALARY OF EMPLOYEES 
SELECT FIRST_NAME, SALARY * NVL(COMMISSION_PCT, 0.1), LAST_DAY(SYSDATE) AS PERIOD_END
FROM EMPLOYEES 
ORDER BY SALARY DESC;

-- QUERY 17:
   -- WAQD THE EMPLOYEES  INFO AND CHECK IF THEY HAVE DEPARTMENTS OR NOT NULLIF DEPT=50
SELECT FIRST_NAME, NULLIF(DEPARTMENT_ID, 50) AS DEPT_CHECK
FROM EMPLOYEES 
ORDER BY DEPARTMENT_ID;

-- QUERY 18: 
--WAQD THE EMPLOYEE SALARY  WITH COALESCE AND  ROUND AS TOTAL COMMISSION EMPLOYEE GETS
SELECT FIRST_NAME, ROUND(COALESCE(COMMISSION_PCT, 0.1)*SALARY, -2) AS TOTAL_COMP
FROM EMPLOYEES 
ORDER BY TOTAL_COMP DESC;

-- QUERY 19:
-- WAQD THE  EMPLOYEE_ID AS LOGIN WITH PHONENUMBER INTIALS AND ANIVERSARY DATE AND THEIR TENURE AND WEEKLY TAKSX PAID BY THEM AND LAST_NAME CONTAINS Z IN LOWERCASE ??
SELECT 
UPPER(SUBSTR(FIRST_NAME, 1, 3)) || SUBSTR(PHONE_NUMBER, -3) AS LOGIN_ID,
TRUNC(NVL(HIRE_DATE, SYSDATE), 'MM') AS ANNIVERSARY_MONTH,
TRUNC(MONTHS_BETWEEN(SYSDATE, NVL(HIRE_DATE, SYSDATE))) AS TENURE_MONTHS,
ROUND((SALARY * 0.14) / 4) AS WEEKLY_TAX
FROM EMPLOYEES
WHERE INSTR(LOWER(LAST_NAME), 'z') > 0
ORDER BY WEEKLY_TAX DESC;

-- QUERY 20:
--  WAQD THE SHORT NAME UPTO 5 CHARACTER IF REAL NAME IS GRATER THAN 6
SELECT 
NVL2(SUBSTR(FIRST_NAME, 6, 1), SUBSTR(FIRST_NAME, 1, 5) || '..', FIRST_NAME) AS SHORT_NAME
FROM EMPLOYEES;

-- QUERY 21: NVL2: DEPT STATUS
SELECT DEPARTMENT_NAME, NVL2(MANAGER_ID, 'MANAGED', 'UNMANAGED') AS STATUS
FROM DEPARTMENTS 
ORDER BY MANAGER_ID NULLS LAST;

-- QUERY 22: NULLIF: NULL IF LOCATION_ID=1700
SELECT DEPARTMENT_NAME, NULLIF(LOCATION_ID, 1700) AS LOC_CHECK
FROM DEPARTMENTS 
ORDER BY LOCATION_ID;

-- QUERY 23: 
--  WAQD THE MGR USING COALESCE FUNCTION AND  FULL DEPT INFO
SELECT COALESCE(MANAGER_ID, 0) AS MGR, DEPARTMENT_NAME, LOCATION_ID
FROM DEPARTMENTS 
ORDER BY DEPARTMENT_NAME;

-- QUERY 24: 
--WAQD DEPARTMENT NAMES AND THEIR BUDGETS, WHERE MISSING MANAGER IDS ARE TREATED AS 100, THE RESULT IS MULTIPLIED BY 1000
SELECT DEPARTMENT_NAME, ROUND(NVL(MANAGER_ID, 100)*1000, -3) AS BUDGET
FROM DEPARTMENTS 
ORDER BY BUDGET DESC;

-- QUERY 25: WRITE A QUESTION TO DISPLAY LOCATION OF DEPTS AND REPLACE WITH HEADQUATERS IF NO DEPARTMENTS
SELECT UPPER(NVL2(LOCATION_ID, 'HAS LOCATION', 'HEADQUARTERS')) AS LOC_STATUS
FROM DEPARTMENTS 
ORDER BY DEPARTMENT_ID;



