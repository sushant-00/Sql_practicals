--QUERY 1:
  --WAQD THE FULL_NAME , WHERE FIRST_NAME STARTS WITH STEVEN AND HAS EXACT LENGTH  6??
  SELECT CONCAT(CONCAT(FIRST_NAME ,' ') , LAST_NAME) AS FULL_NAME
  FROM EMPLOYEES
  WHERE UPPER(FIRST_NAME) LIKE 'STEVEN'
  AND LENGTH(FIRST_NAME) = 6;
  
--QUERY 2:
  -- WAQD THE NAMES AND SALARY WITH RESPECTIVE DEPARTMENT AND SORT BY EMPLOYEE_ID
  SELECT CONCAT(CONCAT(FIRST_NAME , ' '), LAST_NAME) AS FULL_NAME,
  CONCAT (CONCAT('FOR DEPARTMENT ', CONCAT('SALARY IS  :', SALARY)  ) , DEPARTMENT_ID ) AS SAL_PER_DEPT
  FROM EMPLOYEES 
  ORDER BY EMPLOYEE_ID;
  
