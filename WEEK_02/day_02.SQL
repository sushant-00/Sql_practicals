--QUERY 1:
  -- WAQD THE FULL_NAME , WHERE FIRST_NAME STARTS WITH S AND HAS EXACT LENGTH  6  AND CALCULAT ENDDATE OF HIS PROHIBITION PERIOD  WHICH WAS 3 MONTHS?
    SELECT CONCAT(CONCAT(FIRST_NAME ,' ') , LAST_NAME) AS FULL_NAME ,
	ADD_MONTHS(HIRE_DATE , 3) AS PROHIBITION_PERIOD
	FROM EMPLOYEES
	WHERE LENGTH(FIRST_NAME) = 6
	AND FIRST_NAME LIKE 'S%'
	ORDER BY EMPLOYEE_ID;
	
