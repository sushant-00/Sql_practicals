--QUERY 1:
-- WAQD THE COUNT OF EMPLOYEE WHO NOT COMPLETED 22 YEARS OF EXPERIENCE IN THE COMPANY

SELECT COUNT(ROUND(MONTHS_BETWEEN(SYSDATE,HIRE_DATE)/12,2)) AS CNT
FROM EMPLOYEES
WHERE ROUND(MONTHS_BETWEEN(SYSDATE,HIRE_DATE)/12,2)<22;

-- QUERY 2:
-- WAQD  THE NUMBER OF EMPLOYEES IN EACH DEPARTMENT WHO HAVE MORE THAN 22 YEARS OF WORK EMPERIENCE
SELECT DEPARTMENT_ID,COUNT(ROUND(MONTHS_BETWEEN(SYSDATE,HIRE_DATE)/12,2)) AS CNT
FROM EMPLOYEES
WHERE ROUND(MONTHS_BETWEEN(SYSDATE,HIRE_DATE)/12,2)> 20
GROUP BY DEPARTMENT_ID;

-- QUERY 3:
--WAQD  THE MAXIMUM AND MINIMUM ANNUAL SALARY FOR EACH DEPARTMENT 
SELECT DEPARTMENT_ID,MAX(SALARY*12) AS MAX_ANNUAL,
MIN(SALARY*12) AS MIN_ANNUAL
FROM EMPLOYEES
GROUP BY DEPARTMENT_ID;


-- QUERY 4:
--WAQD DEPARTMENTS THAT HAVE AT LEAST ONE EMPLOYEE EARING MORE THAN 100000 ANNUALLY AND SHOULD HAVE COUNT GREATER THAN 0??
SELECT DEPARTMENT_ID,COUNT(SALARY*12)
FROM EMPLOYEES
WHERE (SALARY*12)>100000
GROUP BY DEPARTMENT_ID
HAVING COUNT(SALARY*12) > 0;


-- QUERY 5:
--WAQ DISPLAY JOB AND DEPARTMENT WISE TOTAL SALARY FOR GROUPS HAVING MORE THAN 4 EMPLOYEES.

SELECT JOB_ID, DEPARTMENT_ID, SUM(SALARY) AS TOTAL_SALARY
FROM EMPLOYEES
GROUP BY JOB_ID, DEPARTMENT_ID
HAVING COUNT(*) > 4;

--QUERY 6:
--WAQ DISPLAY DEPARTMENT WISE AVERAGE SALARY FOR DEPARTMENTS WHOSE AVERAGE SALARY IS GREATER THAN 5000.

SELECT DEPARTMENT_ID, ROUND(AVG(SALARY)) AS AVG_SALARY
FROM EMPLOYEES
GROUP BY DEPARTMENT_ID
HAVING AVG(SALARY) > 5000;


-- QUERY 7:
-- WAQ DISPLAY JOB WISE MAX EXPERIENCE FOR JOBS HAVING MAX EXPERIENCE OF MORE THAN A DECADE  YEARS.

