-- QUERY 18:
--WAQTD DISPLAY JOB ID, FIRST NAME, LAST NAME AND AVERAGE SALARY OF EMPLOYEES WHO WERE HIRED BEFORE 01-JAN-2005, GROUP THE DATA BY JOB ID,
--FIRST NAME AND LAST NAME, AND DISPLAY THE RESULT IN ASCENDING ORDER OF AVERAGE SALARY

SELECT JOB_ID,FIRST_NAME,LAST_NAME,AVG(SALARY) AS AVG_SALARY
FROM EMPLOYEES
WHERE HIRE_DATE < TO_DATE('01-JAN-2005','DD-MON-YYYY')
GROUP BY JOB_ID,FIRST_NAME,LAST_NAME
ORDER BY AVG(SALARY);

