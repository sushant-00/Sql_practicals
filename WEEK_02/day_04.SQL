-- QUERY 1:
   -- WAQD THE MAX SALARY OF EMPLOYEES AND MIN AND AVG SALARY  WHERE  EMPLOYEE_ID BETWEEN 100 - 107??
SELECT  MAX(SALARY) AS MAX_SALARY , MIN(SALARY) , AVG(SALARY)
FROM EMPLOYEES 
WHERE EMPLOYEES_ID BETWEEN 100 AND 107;
   
   
 -- QUERY 2:
    
 -- WAQD THE COUNT OF EMPLOYEES IN EVERY DEPARTMENTS
SELECT DEPARTMENT_ID , COUNT(EMPLOYEE_ID)
FROM EMPLOYEES
GROUP BY DEPARTMENT_ID
ORDER BY DEPARTMENT_ID;
	
	
