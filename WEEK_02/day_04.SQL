-- QUERY 15:
--YEAR + DEPARTMENT WISE EMPLOYEE COUNT (DATE + MULTI-GROUP)
SELECT TO_CHAR(HIRE_DATE, 'YYYY') AS HIRE_YEAR,
       DEPARTMENT_ID,
       COUNT(*) AS TOTAL_EMPLOYEES
FROM EMPLOYEES
GROUP BY TO_CHAR(HIRE_DATE, 'YYYY'), DEPARTMENT_ID
ORDER BY HIRE_YEAR, TOTAL_EMPLOYEES DESC;

-- QUERY 16:
-- DEPARTMENT + JOB WISE AVERAGE SALARY (ORDER BY AGGREGATE)
SELECT DEPARTMENT_ID,
       JOB_ID,
       ROUND(AVG(SALARY), 2) AS AVG_SALARY
FROM EMPLOYEES
GROUP BY DEPARTMENT_ID, JOB_ID
ORDER BY AVG_SALARY DESC;

-- QUERY 17:
  -- JOB + FIRST LETTER OF NAME WISE TOTAL SALARY
SELECT JOB_ID,
       SUBSTR(FIRST_NAME, 1, 1) AS FIRST_LETTER,
       SUM(SALARY) AS TOTAL_SALARY
FROM EMPLOYEES
GROUP BY JOB_ID, SUBSTR(FIRST_NAME, 1, 1)
ORDER BY JOB_ID, FIRST_LETTER;

-- QUERY 18:
   --- DEPARTMENT + HIRE MONTH WISE MAXIMUM SALARY
SELECT DEPARTMENT_ID,
       TO_CHAR(HIRE_DATE, 'MON') AS HIRE_MONTH,
       MAX(SALARY) AS MAX_SALARY
FROM EMPLOYEES
GROUP BY DEPARTMENT_ID, TO_CHAR(HIRE_DATE, 'MON')
ORDER BY DEPARTMENT_ID, HIRE_MONTH;

-- QUERY 19:
    -- Department + job wise average monthly salary (numeric + filter + order)
SELECT DEPARTMENT_ID,
       JOB_ID,
       ROUND(AVG(SALARY/12), 2) AS AVG_MONTHLY_SALARY
FROM EMPLOYEES
WHERE SALARY IS NOT NULL
GROUP BY DEPARTMENT_ID, JOB_ID
ORDER BY DEPARTMENT_ID, AVG_MONTHLY_SALARY DESC;

-- QUERY 20:
