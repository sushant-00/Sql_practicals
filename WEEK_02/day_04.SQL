--- QUERY 8:
   -- WAQD THE AVERAGE SALARY PER JOB (ORDERED)
SELECT JOB_ID, ROUND(AVG(SALARY), 2) AS AVG_SALARY
FROM EMPLOYEES
GROUP BY JOB_ID
ORDER BY AVG_SALARY DESC;

