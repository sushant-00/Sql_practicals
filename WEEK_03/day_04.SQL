-- 1. WAQD DETAILS OF EMPLOYEES AND DEPARTMENTS THEY BELONG TO, INCLUDING DEPARTMENTS BUT DOESN'T HAVE ANY EMPLOYEES WORKING IN IT 
-- AND ALSO EMPLOYEES WHO ARE NOT ASSIGNED TO ANY DEPARTMENT, JOIN ON DEPARTMENT ID AND RETURN THOSE EMPLOYEES WHO ARE HIRED IN YEAR 2003 AND WHOSE SALARY LESS THAN 20000.

SELECT E.EMPLOYEE_ID, E.FIRST_NAME, E.LAST_NAME, E.HIRE_DATE, TO_CHAR(E.HIRE_DATE,'YYYY') AS NEW_YEAR, E.SALARY
FROM EMPLOYEES E FULL JOIN DEPARTMENTS D
ON (E.DEPARTMENT_ID = D.DEPARTMENT_ID)
WHERE TO_CHAR(E.HIRE_DATE,'YYYY') = '2003' AND E.SALARY > 20000;

-- 2. WAQD EMPLOYEE ID, FIRST NAME, LAST NAME, JOB TITLE, MIN SALARY, MAX SALARY OF EMPLOYEES AND JOBS TABLE, APPLY FULL JOIN ON JOB ID, 
-- WHOSE JOB_TITLE IS Administration Vice President

SELECT E.EMPLOYEE_ID, E.FIRST_NAME, E.LAST_NAME, J.JOB_TITLE, J.MIN_SALARY, J.MAX_SALARY
FROM EMPLOYEES E FULL JOIN JOBS J
ON (J.JOB_ID = E.JOB_ID)
WHERE J.JOB_TITLE = 'Administration Vice President';

-- 3. WAQD TOTAL MIN SALARY OF EMPLOYEES ON EMPLOYEES AND JOBS TABLE, APPLY FULL JOIN ON JOB ID, 
-- WHOSE JOB_TITLE IS PRGRAMMER

SELECT SUM(MIN_SALARY) AS MIN_SAL
FROM EMPLOYEES E FULL JOIN JOBS J
ON (E.JOB_ID = J.JOB_ID)
WHERE JOB_TITLE = 'Programmer';

-- 4. WAQD TOTAL MIN SALARY OF EMPLOYEES ON EMPLOYEES AND JOBS TABLE, APPLY FULL JOIN ON JOB ID, 
-- WHOSE JOB_TITLE IS STOCK MANAGER

SELECT SUM(MAX_SALARY) AS MIN_SAL
FROM EMPLOYEES E FULL JOIN JOBS J
ON (E.JOB_ID = J.JOB_ID)
WHERE JOB_TITLE = 'Stock Manager';

-- 5. WAQD JOB_TITLE WISE COUNT OF EMPLOYEES ON EMPLOYEES AND JOBS TABLE, APPLY FULL JOIN ON JOB ID.

SELECT JOB_TITLE, COUNT(*) AS CNT
FROM EMPLOYEES E FULL JOIN JOBS J
ON (E.JOB_ID = J.JOB_ID)
GROUP BY JOB_TITLE;

-- 6. WAQD JOB ID WISE AVERAGE OF MINIMUM SALARY OF EMPLOYEES ON EMPLOYEES AND JOBS TABLE, APPLY FULL JOIN ON JOB ID.

SELECT J.JOB_ID, AVG(MIN_SALARY) AS AVG_SAL
FROM EMPLOYEES E FULL JOIN JOBS J
ON (E.JOB_ID = J.JOB_ID)
GROUP BY J.JOB_ID;

-- 7. WAQD EMPLOYEE ID, FIRST_NAME, LAST NAME, JOB_TITLE OF EMPLOYEES ON EMPLOYEES AND JOBS TABLE, APPLY FULL JOIN ON JOB ID, WHOSE AVG MINIMUM SALARY IS GREATER THAN 5000

SELECT E.EMPLOYEE_ID, E.FIRST_NAME, E.LAST_NAME, J.JOB_TITLE, AVG(MIN_SALARY) AVG_MIN_SAL
FROM EMPLOYEES E FULL JOIN JOBS J
ON (E.JOB_ID = J.JOB_ID)
GROUP BY E.EMPLOYEE_ID, E.FIRST_NAME, E.LAST_NAME, J.JOB_TITLE
HAVING AVG(MIN_SALARY) > 5000;

-- 8. WAQD EMPLOYEE ID, FIRST_NAME, LAST NAME, JOB_TITLE OF EMPLOYEES ON EMPLOYEES AND JOBS TABLE, APPLY FULL JOIN ON JOB ID, 
-- WHOSE AVG MINIMUM SALARY IS EQUAL TO 2008 AND FIRST_NAME START WITH 'J'
 
SELECT E.EMPLOYEE_ID, E.FIRST_NAME, E.LAST_NAME, J.JOB_TITLE, AVG(MIN_SALARY) AVG_MIN_SAL
FROM EMPLOYEES E FULL JOIN JOBS J
ON (E.JOB_ID = J.JOB_ID)
GROUP BY E.EMPLOYEE_ID, E.FIRST_NAME, E.LAST_NAME, J.JOB_TITLE
HAVING AVG(MIN_SALARY) = 2008 AND FIRST_NAME LIKE 'J%';

-- 9. WAQD DEPARTMENT_ID, DEPARTMENT_NAME, MANAGER ID, LOCATION ID, STREET ADDRESS, POSTAL CODE, CITY, STATEPROVINCE, COUNTRY_ID OF DEPARTMENTS
-- ON DEPARTMENTS AND LOCATIONS TABLE, APPLY LEFT JOIN ON LOCATION_ID

SELECT D.DEPARTMENT_ID, D.DEPARTMENT_NAME, D.MANAGER_ID, L.LOCATION_ID, L.STREET_ADDRESS,
		L.POSTAL_CODE, L.CITY, L.STATE_PROVINCE, L.COUNTRY_ID
