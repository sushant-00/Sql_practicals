-- 11. WAQD DEPARTMENT_ID, DEPARTMENT_NAME, MANAGER ID, LOCATION ID, STREET ADDRESS, POSTAL CODE, CITY, STATEPROVINCE, COUNTRY_ID OF DEPARTMENTS
-- ON DEPARTMENTS AND LOCATIONS TABLE, APPLY RIGHT JOIN ON LOCATION_ID WHOSE STATE PROVINCE IS NULL

SELECT D.DEPARTMENT_ID, D.DEPARTMENT_NAME, D.MANAGER_ID, L.LOCATION_ID, L.STREET_ADDRESS, 
        L.POSTAL_CODE, L.CITY, L.STATE_PROVINCE, L.COUNTRY_ID
FROM DEPARTMENTS D RIGHT JOIN LOCATIONS L
ON (D.LOCATION_ID = L.LOCATION_ID)
WHERE STATE_PROVINCE IS NULL;

-- 12. WAQD DEPARTMENT NAME WISE COUNT OF MANAGERS ON DEPARTMENTS AND LOCATIONS TABLE, APPLY RIGHT JOIN ON LOCATION ID.

SELECT D.DEPARTMENT_NAME, COUNT(MANAGER_ID) AS CNT
FROM DEPARTMENTS D RIGHT JOIN LOCATIONS L
ON (D.LOCATION_ID = L.LOCATION_ID)
GROUP BY D.DEPARTMENT_NAME;

-- 13. WAQD 'FIRST_NAME, joined the company on, HIRE_DATE' AS EMP INFO, 'Offered role of, JOB_TITLE, on date, HIRE_DATE AFTER 2 YEARS' AS PROMOTION DETAILS OF 
-- EMPLOYEES AND JOBS TABLE, JOIN ON JOB_ID AND INCREMENT SALARY BY 70% AS SALARY AFTER PROMOTION IF SALARY GREATER THAN 10000

SELECT (E.FIRST_NAME ||' ' || E.LAST_NAME|| ' joined the company on ' || TO_CHAR(E.HIRE_DATE,'DD-MON-YYYY')) 
        AS EMP_INFO,
        E.SALARY,
        ('Offered role of '|| J.JOB_TITLE || ' on date ' || TO_CHAR(ADD_MONTHS(E.HIRE_DATE,24),'DD-MON-YYYY')) 
        AS PROMOTION_DETAILS,
        (E.SALARY+(E.SALARY*0.7)) AS SALARY_AFTER_PROMOTION
FROM EMPLOYEES E FULL JOIN JOBS J
ON (J.JOB_ID = E.JOB_ID)
WHERE SALARY > 10000;

-- 14. WAQD NAME OF EMPLOYEES WORKING UNDER MANAGER Neena Kochhar

SELECT E.EMPLOYEE_ID, CONCAT(CONCAT(M.FIRST_NAME,' '), M.LAST_NAME) AS EMP_NAME, CONCAT(CONCAT(E.FIRST_NAME,' '),E.LAST_NAME) AS MANAGER_NAME
