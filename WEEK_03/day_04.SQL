-- 10. WAQD DEPARTMENT_ID, DEPARTMENT_NAME, MANAGER ID, LOCATION ID, STREET ADDRESS, POSTAL CODE, CITY, STATEPROVINCE, COUNTRY_ID OF DEPARTMENTS
-- ON DEPARTMENTS AND LOCATIONS TABLE, APPLY LEFT JOIN ON LOCATION_ID WHOSE COUNTRY ID IS US AND PROVINCE STATE IS Washington

SELECT D.DEPARTMENT_ID, D.DEPARTMENT_NAME, D.MANAGER_ID, L.LOCATION_ID, L.STREET_ADDRESS,
		L.POSTAL_CODE, L.CITY, L.STATE_PROVINCE, L.COUNTRY_ID
