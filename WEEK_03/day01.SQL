-- QUERY 1:
   --WAQD THE DEPARTMENTS FOR ALL EMPLOYEES WHO ARE ASSIGNED MANAGER PRESENT PRESENT IN BOTH DEPARTMENTS AND EMPLOYEES 
SELECT E.FIRST_NAME ,E.JOB_ID, E.SALARY,D.DEPARTMENT_NAME,E.MANAGER_ID
FROM EMPLOYEES E JOIN DEPARTMENTS D
ON E.MANAGER_ID = D.MANAGER_ID;

-- QUERY 2:
   -- WAQD THE  DEPARTMENT NAME WHERE EMPLOYEES HAVE  MANAGER ID IS LIKE 145 
SELECT E.FIRST_NAME ,E.JOB_ID, E.SALARY,D.DEPARTMENT_NAME,E.MANAGER_ID
FROM EMPLOYEES E JOIN DEPARTMENTS D
ON E.MANAGER_ID = D.MANAGER_ID
WHERE E.MANAGER_ID = 145;

-- QUERY 3:
   -- WAQD FIND THE  DEPARTMENT WHERE AVG SALARY IS GREATER THAN 5000 AND SORT BY AVG SALARY??
   
SELECT D.DEPARTMENT_NAME , ROUND(AVG(SALARY)) AS AVG_SAL_DEPT
FROM EMPLOYEES E JOIN DEPARTMENTS D
ON E.DEPARTMENT_ID = D.DEPARTMENT_ID
GROUP BY D.DEPARTMENT_NAME
HAVING AVG(E.SALARY) > 5000
ORDER BY AVG_SAL_DEPT DESC  ;

-- QUERY 4:
  --WAQD DEPARTMENT WISE MAX SALARY GREATER THAN 7500 BUT FOR THOSE EMPLOYEES WHOSE LAST_NAME HAS LENGTH GREATER THAN 6 AND DISPLAY DEPATMENT_NAMES IN UPPER CASE???
SELECT UPPER(D.DEPARTMENT_NAME) AS DEPT_NAME , MAX(SALARY) AS MAX_SALARY
FROM EMPLOYEES E JOIN DEPARTMENTS D
ON E.DEPARTMENT_ID = D.DEPARTMENT_ID
WHERE LENGTH(LAST_NAME) > 6
GROUP BY DEPARTMENT_NAME
HAVING MAX(SALARY) > 7500
ORDER BY MAX_SALARY DESC;

-- QUERY 5:
   -- WAQD THE LOW VALUE  DEPARTMENT ALONG WITH THEIR MIN SALARYS GREATER THAN 1000 AND FOR THOSE EMPLOYEES EARNNG LESS THAN 5000 ??
SELECT UPPER(D.DEPARTMENT_NAME) AS DEPT_NAME ,MIN(SALARY) AS MIN_SALARY
FROM EMPLOYEES E JOIN DEPARTMENTS D
ON E.DEPARTMENT_ID = D.DEPARTMENT_ID 
WHERE SALARY < 5000
GROUP BY DEPARTMENT_NAME 
HAVING MIN(SALARY) > 1000
ORDER BY MIN_SALARY DESC;

-- QUERY 6:
   -- WRITE A QUERY TO DISPLAY  DEPARTMENT NAME AND THEIR TOTAL SALARYS WHERE FOR ONLY THOSE EMPLOYEES HIREDED ON MONDAY
SELECT D.DEPARTMENT_NAME AS DEPT_NAME , SUM(SALARY) AS TOTAL_SAL
FROM EMPLOYEES E JOIN DEPARTMENTS D 
ON E.DEPARTMENT_ID = D.DEPARTMENT_ID
WHERE TO_CHAR(HIRE_DATE , 'DAY') LIKE 'MONDAY%'
GROUP BY DEPARTMENT_NAME;
  
-- QUERY 7:
   -- WRITE A QUERY TO DISPLAY DEPARTMENT WHOSE TOTAL SALARY SPENDING EXCEDS 50000 AND AND DISPLAY BETWEEN YRAR 2003 OR  2005??
SELECT DEPARTMENT_NAME, SUM(SALARY) AS TOTAL_SAL
FROM EMPLOYEES E JOIN DEPARTMENTS D
ON E.DEPARTMENT_ID = D.DEPARTMENT_ID
WHERE TO_CHAR(HIRE_DATE , 'YYYY') LIKE '2003'
OR TO_CHAR(HIRE_DATE , 'YYYY') LIKE '2005'
GROUP BY DEPARTMENT_NAME
HAVING SUM(SALARY) > 50000;

-- QUERY 8:
   -- WAQ HIGH SALARY DISPARITY DEPARTMENTS  BETWEEN EMPLOYEES WHEN DIFF OF SALARY  IS GREATER THAN AVG SALARY??
SELECT D.DEPARTMENT_NAME ,MAX(SALARY) , MIN(SALARY), (MAX(SALARY)-MIN(SALARY)) AS SAL_DISPARITY
FROM EMPLOYEES E JOIN DEPARTMENTS D 
ON E.DEPARTMENT_ID = D.DEPARTMENT_ID
GROUP BY DEPARTMENT_NAME
HAVING (MAX(SALARY)-MIN(SALARY))> AVG(SALARY);

-- QUERY 9:
   -- WAQD SENIOR DEPARTMENS WITH MORE THAN 10 YRS OF EXP AND EMPLOYEE COUNT MORE THAN 5??
   
SELECT DEPARTMENT_NAME , COUNT(EMPLOYEE_ID) AS EMP_CNT 
FROM EMPLOYEES E  JOIN DEPARTMENTS D
ON E.DEPARTMENT_ID= D.DEPARTMENT_ID
WHERE (MONTHS_BETWEEN(SYSDATE , HIRE_DATE)/12) > 10
GROUP BY DEPARTMENT_NAME
HAVING COUNT(EMPLOYEE_ID) > 5;

-- QUERY 10:
    --WAQD THE DEPARTMENT NAME WISE EPLOYEES HIRED DURING SUMMER MONTHS AND AT LEAST 1 HIRE ??
SELECT DEPARTMENT_NAME ,  COUNT(EMPLOYEE_ID)AS EMP_NO
FROM EMPLOYEES E INNER JOIN DEPARTMENTS D
ON E.DEPARTMENT_ID = D.DEPARTMENT_ID
WHERE TRIM(TO_CHAR(HIRE_DATE , 'MONTH')) IN ('JUNE' , 'JULY' , 'AUGUST')
GROUP BY DEPARTMENT_NAME
HAVING COUNT(EMPLOYEE_ID)>= 1;

-- QUERY 11:
   -- WAQD  DEPARTMENTS THAT HAVE AT LEAST 1 DIFFERENT JOB ROLES  AND AN AVERAGE SALARY OF EMPLOYEES (THOSE EARNING > 8,000) EXCEEDING 10,000.
SELECT DEPARTMENT_NAME , COUNT(DISTINCT JOB_ID) , ROUND(AVG(SALARY))
FROM EMPLOYEES E JOIN  DEPARTMENTS D
ON E.DEPARTMENT_ID = D.DEPARTMENT_ID
WHERE SALARY > 8000
GROUP BY DEPARTMENT_NAME
HAVING  AVG(SALARY)> 10000;

-- QUERY 12:
   -- WAQD THE DEPARTMENTS WHERE THE SUM OF THE LENGTHS OF ALL EMPLOYEE NAMES IN THAT DEPARTMENT EXCEEDS 50 CHARACTERS, BUT ONLY FOR EMPLOYEES WHOSE SALARIES ARE NOT NULL.
   
SELECT D.DEPARTMENT_NAME , SUM(LENGTH(E.FIRST_NAME || E.LAST_NAME)) AS TOTAL_NAME_LENGTH
FROM EMPLOYEES E
INNER JOIN DEPARTMENTS D ON E.DEPARTMENT_ID = D.DEPARTMENT_ID
WHERE E.SALARY IS NOT NULL
GROUP BY D.DEPARTMENT_NAME
HAVING SUM(LENGTH(E.FIRST_NAME || E.LAST_NAME)) > 50;


-- QUERY 13:
   --COUNT HOW MANY EMPLOYEES IN EACH DEPARTMENT EARN MORE THAN THE "BASE" OF 5,000 AFTER THEIR SALARY IS TRUNCATED (TRUNC). ONLY SHOW DEPARTMENTS WITH MORE THAN 5 SUCH EMPLOYEES

SELECT D.DEPARTMENT_NAME, COUNT(E.EMPLOYEE_ID)
FROM EMPLOYEES E
INNER JOIN DEPARTMENTS D ON E.DEPARTMENT_ID = D.DEPARTMENT_ID
WHERE TRUNC(E.SALARY) > 5000
GROUP BY D.DEPARTMENT_NAME
HAVING COUNT(E.EMPLOYEE_ID) > 5;

-- QUERY 14:
   -- FIND DEPARTMENTS IN LOCATION_ID 1700 WHERE THE TOTAL POTENTIAL COMMISSION (SALARY × COMMISSION %) FOR EMP IS OVER 10,000. USE NVL TO HANDLE NULL COMMISSIONS.
   
SELECT D.DEPARTMENT_NAME, SUM(E.SALARY * NVL(E.COMMISSION_PCT, 0)) AS TOTAL_COMM
FROM EMPLOYEES E
INNER JOIN DEPARTMENTS D ON E.MANAGER_ID = D.MANAGER_ID
WHERE D.LOCATION_ID = 1700
GROUP BY D.DEPARTMENT_NAME
HAVING SUM(E.SALARY * NVL(E.COMMISSION_PCT, 0)) > 10000;

