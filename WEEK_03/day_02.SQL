-- QUERY 1:
   -- WAQD THE COUNT OF EMPLOYEES WHO HAVE MANAGER_ID PRESNET IN DEPARTMENTS AS WELL AS ALL REMAING RECORDS OF EMPLOYEES
SELECT COUNT(EMPLOYEE_ID) AS CNT
FROM EMPLOYEES E LEFT OUTER JOIN  DEPARTMENTS D 
ON E.DEPARTMENT_ID = D.DEPARTMENT_ID;

-- QUERY 2:
  --WAQD THE SALARYS IN DOLLARS AND MOTHS OF SERVICE FROM HIREDATE AND TOTAL NUMBER OF EMPLOYEES ALONG WITH THEIR RESPECTIVE DEPARTMENTS??
  
SELECT (E.FIRST_NAME||E.LAST_NAME) AS FULL_NAME , D.DEPARTMENT_NAME , (RTRIM(TO_CHAR(E.SALARY))||'$')AS SAL_DOLLARS, TRUNC(MONTHS_BETWEEN(SYSDATE ,HIRE_DATE)) AS MONTHS_SERVCE
FROM EMPLOYEES E LEFT OUTER JOIN DEPARTMENTS D
ON(E.DEPARTMENT_ID = D.DEPARTMENT_ID);

-- QUERY 3:
  -- WAQD THE TOTAL NUMBERS OF EMPLOYEES WITH THEIR DEPARTMENTS BETWEN YEAR  2003 AND 2005 AND SALARY GRATER THAN 4000 
  
 SELECT (E.FIRST_NAME||E.LAST_NAME) AS FULL_NAME , D.DEPARTMENT_NAME ,TO_CHAR(HIRE_DATE , 'YEAR') AS YOJ
 FROM EMPLOYEES E LEFT OUTER JOIN DEPARTMENTS D
 ON (E.DEPARTMENT_ID = D.DEPARTMENT_ID)
 WHERE ( TO_CHAR(HIRE_DATE, 'YYYY') >= '2003' AND TO_CHAR(HIRE_DATE,'YYYY') <= '2005')
 AND SALARY > 4000;
 
 -- QUERY 4:
    -- WAQD THE TOTAL EMPLOYEES WITH DEPARTMENTS IN UPPER_CASE AND TOTAL SALARYS OF EACH EMPLOYEES ALONG WITH TENURE AT THE COMPANY AND ORDER BY SALARY
	
SELECT (E.FIRST_NAME||E.LAST_NAME) AS FULL_NAME , UPPER(D.DEPARTMENT_NAME) AS DEPT_NAME, ROUND((SALARY + SALARY*NVL(COMMISSION_PCT,0))*12) AS TOTAL_SALARY
, ROUND(MONTHS_BETWEEN(SYSDATE,HIRE_DATE),2)/12||'YEARS' AS TENURE
FROM EMPLOYEES E LEFT OUTER JOIN DEPARTMENTS D
ON (E.DEPARTMENT_ID = D.DEPARTMENT_ID)
ORDER BY SALARY;

-- QUERY 5:
   -- WAQD THE TOTAL EMPLOYEES ALONG WITH THEIR MAX SALARY FOR DIFFERENT AGE GROUPS 
SELECT FIRST_NAME ,  DEPARTMENT_NAME , NVL(RPAD(UPPER(SUBSTR(e.last_name, 1, 3)), 5, '*')|| TO_CHAR(e.hire_date, 'YYMM'), 'VACANT') AS SECURITY_ID
FROM EMPLOYEES E RIGHT OUTER JOIN DEPARTMENTS D
ON (E.DEPARTMENT_ID= D.DEPARTMENT_ID)
ORDER BY EMPLOYEE_ID;

-- QUERY 6:
   -- WAQD THE NULL EMPLOYEES AND NULL DEPARTMENTS AS OPEN POSITIONS AND ANY NULL EMP AS FLOATING EMP WHICH HAS NO DEPT ASSIGNED??
SELECT 
COALESCE(E.LAST_NAME, 'DEPT ONLY') AS EMP_ID,
COALESCE(D.DEPARTMENT_NAME, 'FLOATING EMP') AS DEPT_ID,
NVL2(E.EMPLOYEE_ID, 'ACTIVE', 'POSITION OPEN') AS STATUS
FROM EMPLOYEES E
FULL OUTER JOIN DEPARTMENTS D ON E.DEPARTMENT_ID = D.DEPARTMENT_ID;

-- QUERY 7:
   -- WAQD THE 21 YEAR ANIVERSARY DATE FOR EMPLOYEES AND THEIR AND WHAT DAY IT FALLS
   
SELECT FIRST_NAME , TO_CHAR(ADD_MONTHS(HIRE_DATE , 252) , 'YYYY-MON-DD') AS ANIVERSARY_DATE , TO_CHAR(ADD_MONTHS(HIRE_DATE , 252), 'DAY') AS DAY_ANI
FROM EMPLOYEES E LEFT JOIN DEPARTMENTS D
ON(E.DEPARTMENT_ID = D.DEPARTMENT_ID);

-- QUERY 8:
   -- WAQD THE ALL EMPLOYEES RECORDS AND THEIR DEPARTMENT NAMES WITH INTIAL LETTERS CAPITAL AND DISPLAY THEIR REVIEW DATE AFTER 6 MONTHS OF HIRE??
SELECT FIRST_NAME, DEPARTMENT_NAME, TRUNC(ADD_MONTHS(HIRE_DATE ,6), 'MM') AS REVIEW_DATE
FROM EMPLOYEES E LEFT JOIN DEPARTMENTS D
ON(E.DEPARTMENT_ID = D.DEPARTMENT_ID);

-- QUERY 9:
  -- WAQD THE DEPARTMENT WISE TOTAL SALARY AND AND DISPLAY ZERO IF NOT PRESENT ??
  
SELECT DEPARTMENT_NAME, NVL(SUM(SALARY) ,0) AS TOTAL_SAL
FROM EMPLOYEES E RIGHT JOIN DEPARTMENTS D
ON(E.DEPARTMENT_ID = D.DEPARTMENT_ID)
GROUP BY DEPARTMENT_NAME ;

-- QUERY 10:
    -- WAQD THE AVG , MIN , MAX SALARY DEPARTMENT WISE DISPLAY 0 IF NOT PRESENT ?
	
SELECT DEPARTMENT_NAME , NVL(MAX(SALARY) , 0) , NVL(MIN(SALARY),0) , NVL(AVG(SALARY),0)
FROM EMPLOYEES E RIGHT JOIN DEPARTMENTS D 
ON (E.DEPARTMENT_ID = D.DEPARTMENT_ID)
GROUP BY DEPARTMENT_NAME ;
