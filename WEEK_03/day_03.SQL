-- QUERY 1:
   --WRITE A QURIE TO DISPLAY DIFFERENT NEIGHBOURS OF A COUNTRYS AS ITS NEGIBOURS AND SHOULD NOT INCLUDE ITSELF??
SELECT C.COUNTRY_NAME , Y.COUNTRY_NAME AS NEGIBOURS , Y.REGION_ID
FROM COUNTRIES C JOIN COUNTRIES Y
ON(C.REGION_ID = Y.REGION_ID)
WHERE C.COUNTRY_NAME <> Y.COUNTRY_NAME;

--QUERY 2:
   -- FIND EMPLOYEES HIRED ON THE EXACT SAME DAY AS SOMEONE ELSE IN THEIR DEPARTMENT.
SELECT E1.LAST_NAME, E2.LAST_NAME AS COLLEAGUE, E1.HIRE_DATE
FROM EMPLOYEES E1 JOIN EMPLOYEES E2 ON (E1.DEPARTMENT_ID = E2.DEPARTMENT_ID)
WHERE E1.HIRE_DATE = E2.HIRE_DATE AND E1.EMPLOYEE_ID < E2.EMPLOYEE_ID;

-- QUERY 3:
    -- WAQD THE FIND MANAGERS WHO MANAGE OTHER MANAGERS.
	
SELECT DISTINCT UPPER(M.LAST_NAME) AS EXECUTIVE_MANAGER
FROM EMPLOYEES E 
JOIN EMPLOYEES M ON (E.MANAGER_ID = M.EMPLOYEE_ID)
WHERE M.EMPLOYEE_ID IN (SELECT MANAGER_ID FROM EMPLOYEES);

-- QUERY 4:
   --WAQD THE  ALL DEPARTMENTS AND THEIR CITIES, INCLUDING DEPARTMENTS WITH NO EMPLOYEES AND CITIES WITH NO DEPARTMENTS.
SELECT NVL(D.DEPARTMENT_NAME, 'NO DEPT') AS DEPT, L.CITY
FROM DEPARTMENTS D LEFT OUTER JOIN LOCATIONS L ON (D.LOCATION_ID = L.LOCATION_ID);

-- QUERY 5:
   -- WAQ TO PERFORM A FULL RECONCILIATION OF COUNTRIES AND REGIONS
SELECT NVL2(C.COUNTRY_NAME, C.COUNTRY_NAME, 'UNKNOWN COUNTRY') AS COUNTRY,
       NVL2(R.REGION_NAME, R.REGION_NAME, 'INVALID REGION') AS REGION
FROM COUNTRIES C FULL OUTER JOIN REGIONS R ON (C.REGION_ID = R.REGION_ID);

-- QUERY 6:
    -- WAQ TO CREATE A MASKED PHONE DIRECTORY FOR ALL STAFF AND DEPARTMENTS.
	SELECT CONCAT('***', SUBSTR(E.PHONE_NUMBER, -4)) AS MASKED_PHONE, 
       COALESCE(D.DEPARTMENT_NAME, 'FREELANCE') AS DEPT
FROM EMPLOYEES E FULL OUTER JOIN DEPARTMENTS D ON (E.DEPARTMENT_ID = D.DEPARTMENT_ID);


-- QUERY 7:
   -- WAQD FIND EMPLOYEES HIRED ON A FRIDAY
SELECT E.LAST_NAME, TO_CHAR(E.HIRE_DATE, 'DAY') AS DAY
FROM EMPLOYEES E LEFT OUTER JOIN DEPARTMENTS D ON (E.DEPARTMENT_ID = D.DEPARTMENT_ID)
WHERE TRIM(TO_CHAR(E.HIRE_DATE, 'DAY')) = 'FRIDAY';

-- QUERY 8:
   --WAQD THE FOR DEPARTMENTS WITH NO EMPLOYEES, SHOW A PROJECTED TAX OF 0; FOR OTHERS, CALCULATE TAX EXCLUDING COMMISSION.
   SELECT D.DEPARTMENT_NAME, ROUND(SUM(NVL(E.SALARY, 0) * 0.15), 2) AS TAX
FROM EMPLOYEES E RIGHT OUTER JOIN DEPARTMENTS D ON (E.DEPARTMENT_ID = D.DEPARTMENT_ID)
GROUP BY D.DEPARTMENT_NAME;

-- QUERY 9:
    -- WAQD EMPLOYEES AND THEIR DEPARTMENTS WHERE THE EMPLOYEE'S LAST NAME STARTS WITH A VOWEL AND THE DEPARTMENT NAME ENDS WITH 'ING'.

SELECT E.LAST_NAME, D.DEPARTMENT_NAME
FROM EMPLOYEES E JOIN DEPARTMENTS D ON (E.DEPARTMENT_ID = D.DEPARTMENT_ID)
WHERE LOWER(SUBSTR(E.LAST_NAME, 1, 1)) IN ('A','E','I','O','U')
  AND D.DEPARTMENT_NAME LIKE '%ING';
  
-- QUERY 10:
    -- WAQD THE FIND THE DAY OF THE WEEK FOR EVERYONE’S 10TH ANNIVERSARY, EXCLUDING THOSE IN THE 'IT' DEPARTMENT.
SELECT E.LAST_NAME, INITCAP(TO_CHAR(ADD_MONTHS(E.HIRE_DATE, 120), 'DAY')) AS ANNIV_DAY
FROM EMPLOYEES E LEFT OUTER JOIN DEPARTMENTS D ON (E.DEPARTMENT_ID = D.DEPARTMENT_ID)
WHERE D.DEPARTMENT_NAME <> 'IT' OR D.DEPARTMENT_NAME IS NULL;

-- QUERY 11:
    -- FIND PAIRS OF EMPLOYEES IN THE SAME DEPARTMENT WHO EARN THE EXACT SAME SALARY
	SELECT E1.LAST_NAME, E2.LAST_NAME, E1.SALARY, E1.DEPARTMENT_ID
FROM EMPLOYEES E1 JOIN EMPLOYEES E2 ON (E1.DEPARTMENT_ID = E2.DEPARTMENT_ID)
WHERE E1.SALARY = E2.SALARY AND E1.EMPLOYEE_ID < E2.EMPLOYEE_ID;


-- QUERY 12:
   -- FIND EMPLOYEES WHO SHARE THE SAME FIRST 3 DIGITS OF THEIR PHONE NUMBER WITH THEIR MANAGER.
SELECT E.LAST_NAME, E.PHONE_NUMBER, M.LAST_NAME AS MANAGER
FROM EMPLOYEES E JOIN EMPLOYEES M ON (E.MANAGER_ID = M.EMPLOYEE_ID)
WHERE SUBSTR(E.PHONE_NUMBER, 1, 3) = SUBSTR(M.PHONE_NUMBER, 1, 3);

-- QUERY 13:
  -- WAQ TO COUNT HOW MANY PEOPLE REPORT TO EACH MANAGER WITHIN SPECIFIC DEPARTMENTS.
  

SELECT M.LAST_NAME, COUNT(E.EMPLOYEE_ID) AS CNT
FROM EMPLOYEES E JOIN EMPLOYEES M ON (E.MANAGER_ID = M.EMPLOYEE_ID)
GROUP BY M.LAST_NAME
HAVING COUNT(E.EMPLOYEE_ID) > 2;


-- QUERY 14:
    -- FIND EMPLOYEES WHO ARE NOT ASSIGNED TO ANY DEPARTMENT, BUT SHOW THEIR POTENTIAL CITY VIA THEIR MANAGER'S DEPARTMENT.
SELECT E.LAST_NAME, NVL(D.DEPARTMENT_NAME, 'NO DEPARTMENT') AS DEPT
FROM EMPLOYEES E LEFT OUTER JOIN DEPARTMENTS D ON (E.DEPARTMENT_ID = D.DEPARTMENT_ID)
WHERE E.DEPARTMENT_ID IS NULL;

-- QUERY 15:
   -- WAQ TO LIST ALL COUNTRIES AND ALL REGIONS, INCLUDING REGIONS WITHOUT COUNTRIES AND COUNTRIES WITHOUT REGION
   SELECT C.COUNTRY_NAME, R.REGION_NAME
FROM COUNTRIES C FULL OUTER JOIN REGIONS R ON (C.REGION_ID = R.REGION_ID);

-- QUERY 16:
    --SHOW ALL LOCATION ADDRESSES AND THE NAMES OF DEPARTMENTS THERE; INCLUDE ADDRESSES WITH NO DEPARTMENTS.


SELECT L.STREET_ADDRESS, D.DEPARTMENT_NAME
FROM DEPARTMENTS D RIGHT OUTER JOIN LOCATIONS L ON (D.LOCATION_ID = L.LOCATION_ID);

-- QUERY 17:
   -- WAQD THE  A SIMPLE JOIN TO DISPLAY THE REGION NAME ALONGSIDE COUNTRY ID CODES.

SELECT R.REGION_NAME, C.COUNTRY_ID
FROM REGIONS R
JOIN COUNTRIES C ON (R.REGION_ID = C.REGION_ID);

-- QUERY 18:
   -- WAQD THE USES THE JOBS TABLE ALONE USING  SELF-JOIN TO COMPARE HIGH-PAY ROLES AGAINST LOW-PAY ROLES.
   
SELECT A.JOB_TITLE AS HIGH_PAY_JOB, B.JOB_TITLE AS LOW_PAY_JOB
FROM JOBS A
JOIN JOBS B ON (A.MIN_SALARY > B.MAX_SALARY)
WHERE A.JOB_ID = 'AD_PRES';

--QUERY 19:
    -- SHOWS WHICH COUNTRIES IN THE DATABASE DON'T HAVE A SPECIFIC OFFICE LOCATION ASSIGNED YET.
SELECT C.COUNTRY_NAME, L.LOCATION_ID
FROM COUNTRIES C
LEFT OUTER JOIN LOCATIONS L ON (C.COUNTRY_ID = L.COUNTRY_ID)
WHERE L.LOCATION_ID IS NULL;

-- QUERY 20:
   -- LINKS LOCATIONS AND COUNTRIES TO SEE WHICH NATION HAS THE MOST PHYSICAL OFFICES.
SELECT C.COUNTRY_NAME, COUNT(L.LOCATION_ID) AS OFFICE_COUNT
FROM COUNTRIES C
JOIN LOCATIONS L ON (C.COUNTRY_ID = L.COUNTRY_ID)
GROUP BY C.COUNTRY_NAME;