-- QUERY 10: WAQD DPEART NAME WISE COUNT OF EMP WHOSE DEP IS GRTER THAN 20 AND SALARY GRETER THAN MIN SALARY OF THEIR RSPECTIVE JOBS;

SELECT 
    D.DEPARTMENT_NAME, 
    COUNT(E.EMPLOYEE_ID) AS EMP_COUNT
FROM EMPLOYEES E
JOIN DEPARTMENTS D ON E.DEPARTMENT_ID = D.DEPARTMENT_ID
WHERE E.SALARY > (
    
    SELECT MIN_SALARY 
    FROM JOBS J 
    WHERE J.JOB_ID = E.JOB_ID
)
GROUP BY D.DEPARTMENT_NAME
HAVING COUNT(E.EMPLOYEE_ID) > 20;

