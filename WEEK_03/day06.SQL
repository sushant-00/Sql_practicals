-- QUERY 1: WRITE A QUERY TO DISPLAY HOW MANY EMPLOYEES WORK UNDER A DEPARTMENT , COUNTRY AND CITY THEIR AVG SALARY  FOR UK AND US ONLY AND ORDER BY SALARY??
SELECT C.COUNTRY_NAME,  D.DEPARTMENT_NAME , L.CITY ,COUNT(*) AS CNT ,ROUND ( AVG(E.SALARY)) AS AVG_SAL
FROM EMPLOYEES E LEFT OUTER JOIN DEPARTMENTS D
USING(DEPARTMENT_ID)

JOIN LOCATIONS L
USING(LOCATION_ID)

JOIN COUNTRIES C
USING(COUNTRY_ID) 

WHERE  L.CITY IN (SELECT CITY
                     FROM LOCATIONS 
                     WHERE COUNTRY_ID = 'US'
                     OR COUNTRY_ID = 'UK')
GROUP BY C.COUNTRY_NAME,  D.DEPARTMENT_NAME , L.CITY
ORDER BY AVG(E.SALARY)DESC  ;


