-- QUERY 15: WRITE A Find departments that currently have no employees, but are located in countries where the region is 'Europe'.
SELECT D.DEPARTMENT_NAME
FROM DEPARTMENTS D
LEFT JOIN EMPLOYEES E ON D.DEPARTMENT_ID = E.DEPARTMENT_ID
WHERE E.EMPLOYEE_ID IS NULL
AND D.LOCATION_ID IN (
    SELECT L.LOCATION_ID 
    FROM LOCATIONS L
    JOIN COUNTRIES C ON L.COUNTRY_ID = C.COUNTRY_ID
    WHERE C.REGION_ID = (SELECT REGION_ID FROM REGIONS WHERE REGION_NAME = 'Europe')
);


