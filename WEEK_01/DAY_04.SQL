
--QUERY 1:
  --> WAQD THE EMP_NAME , SALARY , THEIR RESPECTIVE DEPT AND SHOW  HIGHEST SALARY EMPLOYEES FIRST AND SALARY MUST BE GREATER THAN 2000 ??
  
  SELECT (FIRST_NAME||' '||LAST_NAME) AS FULL_NAME ,
  ('WORKING IN DEPARTMENT : ' ||DEPARTMENT_ID ||'HAVING SALARY : '||SALARY) AS SAL_PER_DEPT
  FROM EMPLOYEES 
  WHERE SALARY > 2000
  ORDER BY SALARY DESC;
  
 --QUERY 2:
